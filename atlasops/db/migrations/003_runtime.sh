#!/bin/sh
set -eu
: "${POSTGRES_APP_PASSWORD:?Set POSTGRES_APP_PASSWORD}"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$POSTGRES_APP_PASSWORD" <<'EOSQL'
CREATE ROLE atlasops_runtime LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT CONNECT ON DATABASE atlasops TO atlasops_runtime;
GRANT USAGE ON SCHEMA public TO atlasops_runtime;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO atlasops_runtime;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO atlasops_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO atlasops_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO atlasops_runtime;
EOSQL
